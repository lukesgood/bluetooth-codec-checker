// Release signing is read from keystore.properties (git-ignored) or, failing that,
// from environment variables. Neither the keystore nor its passwords belong in git.
// See keystore.properties.example.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(key: String, env: String): String? =
    keystoreProperties.getProperty(key) ?: System.getenv(env)

val releaseStoreFile = signingValue("storeFile", "BCC_STORE_FILE")
val releaseStorePassword = signingValue("storePassword", "BCC_STORE_PASSWORD")
val releaseKeyAlias = signingValue("keyAlias", "BCC_KEY_ALIAS")
val releaseKeyPassword = signingValue("keyPassword", "BCC_KEY_PASSWORD")
val hasReleaseSigning = listOf(
    releaseStoreFile, releaseStorePassword, releaseKeyAlias, releaseKeyPassword
).all { !it.isNullOrBlank() }

android {
    namespace = "com.bluetoothcodec.checker"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.bluetoothcodec.checker"
        minSdk = 26
        targetSdk = 36
        versionCode = 21
        versionName = "2.0.3"
    }

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = rootProject.file(releaseStoreFile!!)
                storePassword = releaseStorePassword
                keyAlias = releaseKeyAlias
                keyPassword = releaseKeyPassword
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            // Without signing values the release APK is built unsigned.
            signingConfig = signingConfigs.findByName("release")
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

